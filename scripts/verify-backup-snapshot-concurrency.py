"""Exercise concurrent writes only in two named disposable loopback databases."""
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ADMIN = 'postgresql://supabase_admin:postgres@127.0.0.1:54322/postgres'
SOURCE = 'postgresql://supabase_admin:postgres@127.0.0.1:54322/drx_snapshot_fixture'
TARGET = 'postgresql://supabase_admin:postgres@127.0.0.1:54322/drx_snapshot_replay'
DATABASES = ('drx_snapshot_fixture', 'drx_snapshot_replay')
PSQL = os.environ['DRX_REAL_PSQL']
spec = importlib.util.spec_from_file_location('snapshot', Path(__file__).with_name('backup-source-snapshot.py'))
snapshot = importlib.util.module_from_spec(spec)
spec.loader.exec_module(snapshot)


def query(dsn, sql):
    if dsn not in (ADMIN, SOURCE, TARGET):
        raise ValueError('fixture_target_invalid')
    result = subprocess.run([PSQL, dsn, '-X', '-qAt', '--set', 'ON_ERROR_STOP=1'], input=sql,
                            capture_output=True, text=True, timeout=30)
    if result.returncode:
        raise ValueError('fixture_query_failed')
    return result.stdout.strip()


def run():
    keeper = None
    created = []
    try:
        for name in DATABASES:
            query(ADMIN, f'CREATE DATABASE {name};')
            created.append(name)
        schema = 'CREATE SCHEMA auth; CREATE TABLE auth.snapshot_rows(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,value integer NOT NULL);'
        query(SOURCE, schema + ' INSERT INTO auth.snapshot_rows(value) VALUES (10),(20);')
        query(TARGET, schema)
        keeper = subprocess.Popen([PSQL, SOURCE, '-X', '-qAt', '--set', 'ON_ERROR_STOP=1'], stdin=subprocess.PIPE,
                                  stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
        keeper.stdin.write('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY; SELECT pg_export_snapshot();\n')
        keeper.stdin.flush()
        sid = keeper.stdout.readline().strip()
        prefix = snapshot.sql_prefix(sid)
        # A normal writer remains able to update and insert while the snapshot is held.
        query(SOURCE, 'UPDATE auth.snapshot_rows SET value=900 WHERE id=1; INSERT INTO auth.snapshot_rows(value) VALUES (30);')
        frozen = query(SOURCE, prefix + 'SELECT jsonb_agg(to_jsonb(t) ORDER BY id) FROM auth.snapshot_rows t; COMMIT;')
        current = query(SOURCE, 'SELECT jsonb_agg(to_jsonb(t) ORDER BY id) FROM auth.snapshot_rows t;')
        if frozen == current or len(json.loads(frozen)) != 2 or len(json.loads(current)) != 3:
            raise ValueError('concurrent_writer_not_proven')
        with tempfile.TemporaryDirectory(prefix='drx-snapshot-fixture-', dir=os.environ['RUNNER_TEMP']) as directory:
            root = Path(directory).resolve()
            if root.parent != Path(os.environ['RUNNER_TEMP']).resolve():
                raise ValueError('fixture_directory_invalid')
            data = root / 'native.sql'
            with data.open('wb') as output:
                result = subprocess.run(['docker', 'run', '--rm', '--network', 'host', '-e', 'FIXTURE_DATABASE_URL', '-e', 'FIXTURE_SNAPSHOT',
                                         os.environ['SOURCE_DUMP_IMAGE'], 'sh', '-c',
                                         'exec pg_dump "$FIXTURE_DATABASE_URL" --snapshot="$FIXTURE_SNAPSHOT" --data-only --schema=auth',
                                         ], env={**os.environ, 'FIXTURE_DATABASE_URL': SOURCE, 'FIXTURE_SNAPSHOT': sid},
                                        stdout=output, stderr=subprocess.DEVNULL, timeout=60)
            # The snapshot ID is passed as environment, never interpolated into shell source.
            if result.returncode:
                raise ValueError('fixture_dump_failed')
            query(TARGET, data.read_text())
            replay = query(TARGET, 'SELECT jsonb_agg(to_jsonb(t) ORDER BY id) FROM auth.snapshot_rows t;')
            if replay != frozen:
                raise ValueError('frozen_dump_replay_mismatch')
            query(SOURCE, 'INSERT INTO auth.snapshot_rows(value) VALUES (40);')
            rows = Path(__file__).with_name('backup-native-rows.sql')
            checkpoint = root / 'sequence.sql'
            snapshot.sequence_checkpoint(data, rows, checkpoint)
            sequence_sql = checkpoint.read_text().split('SELECT jsonb_build_object(\'kind\',\'sequenceState\'', 1)[1]
            expected = query(TARGET, "SELECT set_config('drx.backup_fingerprint_salt','synthetic',false); SELECT jsonb_build_object('kind','sequenceState'" + sequence_sql).splitlines()[-1]
            actual = query(TARGET, "SELECT jsonb_build_object('kind','sequenceState','identity','auth.snapshot_rows_id_seq','components',jsonb_build_object('state',encode(sha256(convert_to('synthetic'||jsonb_build_array(last_value,is_called)::text,'UTF8')),'hex'))) FROM auth.snapshot_rows_id_seq;")
            if expected != actual or query(SOURCE, 'SELECT last_value FROM auth.snapshot_rows_id_seq;') == query(TARGET, 'SELECT last_value FROM auth.snapshot_rows_id_seq;'):
                raise ValueError('retained_sequence_checkpoint_not_proven')
        return {'status': 'PASS', 'isolatedTarget': True, 'productionMutations': False,
                'concurrentWritesVerified': True, 'sameSnapshotForDumpAndManifest': True,
                'newerRowsExcludedFromSnapshot': True, 'retainedSequenceCheckpointVerified': True}
    finally:
        if keeper and keeper.poll() is None:
            keeper.stdin.write('ROLLBACK;\n\\q\n')
            keeper.stdin.flush()
            keeper.wait(timeout=10)
        # These names are fixed and ADMIN is a literal loopback-only connection.
        for name in reversed(created):
            query(ADMIN, f'DROP DATABASE {name} WITH (FORCE);')


if __name__ == '__main__':
    try:
        proof = run()
        Path('drx-source-snapshot-concurrency-proof.json').write_text(json.dumps(proof) + '\n')
        print('Read-only snapshot and retained sequence checkpoints survived concurrent isolated writes.')
    except (ValueError, OSError, subprocess.SubprocessError):
        print('Isolated snapshot concurrency proof failed; private diagnostics are not published.', file=sys.stderr)
        sys.exit(1)
