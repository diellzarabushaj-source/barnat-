'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=read('antibiotiket.html');
const script=read('antibiotiket-finish.js');
const stylesheet=read('antibiotiket-finish.css');
const catalog=read('antibiotiket-catalog.js');
const core=read('antibiotiket-catalog-core.js');
assert.match(html,/antibiotiket-finish\.js\?v=/);
assert.match(html,/antibiotiket-finish\.css\?v=/);
assert.ok(html.indexOf('antibiotiket-interactions.js')<html.indexOf('antibiotiket-finish.js'),'finish must run after quick-route enhancement');
assert.ok(html.indexOf('antibiotiket-finish.css')<html.indexOf('drx-dashboard-stripe.css'),'canonical Stripe shell must remain last');
assert.match(script,/abx-discovery-rail/);
assert.match(script,/rail\.append\(scope,route\)/);
assert.match(script,/filter\.prepend\(facetHeading\)/);
assert.match(script,/role','group/);
assert.doesNotMatch(script,/calculateDose|calculateMl|authorizedRegimen|approvedBindings|doseMgPerKg/,'Presentation layer must not modify clinical logic');
assert.doesNotThrow(()=>new Function(script));
assert.match(stylesheet,/abx-catalog-heading/);
assert.match(stylesheet,/abx-discovery-rail/);
assert.match(stylesheet,/abx-catalog-search/);
assert.match(stylesheet,/abx-catalog-item-actions/);
assert.match(stylesheet,/Clinical Atlas \+ Clinical Edition convergence/);
assert.match(stylesheet,/V6 Minimal clinical finish/);
assert.match(stylesheet,/color:#b42318/,'Blocked clinical state retains red semantic text');
assert.doesNotMatch(html,/antibiotiket-clinical-edition\.css/,'No redundant stylesheet cascade');
assert.match(catalog,/abx-heading-metrics/,'Registry-driven stats retained in header');
assert.match(catalog,/class="abx-heading-symbol" aria-hidden="true">Rx<\/span>/,'Static 34px-safe monogram instead of unbounded capsule SVG');
assert.doesNotMatch(catalog,/class="abx-heading-symbol"[^>]*><svg/,'Unbounded graphic must never return');
assert.match(stylesheet,/P1 screenshot regression/);
assert.match(stylesheet,/V7 · Quiet Clinical Search/,'Minimal search-focused UI remains in clinical shell');
assert.match(stylesheet,/data-query-active="true"/,'Query hides decorative example chips only while filtering');
assert.match(stylesheet,/min-height:44px/,'Tap targets remain comfortable');
assert.match(stylesheet,/color:#b42318/,'Blocked clinical safety status stays red');
const smartUi=read('antibiotiket-smart-ui.js');
assert.match(smartUi,/root\.dataset\.queryActive=state\.search\.trim\(\)/,'Query state is derived from real search input');
assert.match(smartUi,/navigator\.platform/,'Search shortcut adapts to platform');
assert.doesNotMatch(smartUi,/calculateDose|doseMgPerKg|authorizedRegimen/,'Visual improvements never alter dose calculations');
assert.match(stylesheet,/max-width:34px/);
assert.match(stylesheet,/@media\(max-width:420px\)/);
assert.match(stylesheet,/@media\(prefers-reduced-motion:reduce\)/);
assert.match(stylesheet,/\.abx-catalog-pill\.is-missing/,'Do not visually erase blocked clinical status');
assert.doesNotMatch(html,/https:\/\/(?:unpkg|cdn\.jsdelivr|fonts\.googleapis)\./,'No third-party UI runtime');
assert.match(catalog,/core\.filterAntibiotics/);
assert.match(core,/referenceMatchesProduct/);
console.log('Antibiotics Clinical Atlas design integrity checks passed.');
