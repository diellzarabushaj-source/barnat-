'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const x=JSON.parse(fs.readFileSync(path.join(__dirname,'..','data','drx-first100-source-discovery-wave-a-v1.json'),'utf8'));
assert.equal(x.verifiedProductSpecificCount,16);
assert.equal(x.productSelectionRequiredCount,0);
assert.equal(x.publicationAllowed,false);
const verified=x.rows.filter(r=>r.status.startsWith('verified_product_specific'));
assert.equal(verified.length,15);
assert.ok(verified.every(r=>r.sourceTier==='EMC'&&/^https:\/\/www\.medicines\.org\.uk\/emc\//.test(r.url)));
assert.ok(verified.every(r=>r.section41Present===true&&r.section42Present===true));
assert.ok(x.rows.find(r=>r.canonicalKey==='acenocoumarol').reviewFlags.includes('high_risk_anticoagulant'));
assert.ok(x.rows.find(r=>r.canonicalKey==='amiodarone').reviewFlags.includes('high_risk_antiarrhythmic'));
const alteplase=x.rows.find(r=>r.canonicalKey==='alteplase');
assert.equal(alteplase.status,'verified_product_family_selection');
assert.equal(alteplase.selectionRequiredAtRuntime,true);
assert.equal(alteplase.defaultProduct,null);
assert.equal(alteplase.failClosedOnAmbiguousSelection,true);
assert.equal(alteplase.selectionVariants.length,2);
const systemic=alteplase.selectionVariants.find(v=>v.selectionKey==='systemic_thrombolysis');
const cathflo=alteplase.selectionVariants.find(v=>v.selectionKey==='central_venous_access_device_occlusion');
assert.deepEqual(systemic.presentationsMg,[10,20,50]);
assert.deepEqual(cathflo.presentationsMg,[2]);
assert.ok(systemic.indicationKeys.includes('acute_ischaemic_stroke'));
assert.deepEqual(cathflo.indicationKeys,['occluded_central_venous_access_device']);
assert.equal(systemic.section41Present,true);
assert.equal(systemic.section42Present,true);
assert.equal(cathflo.section41Present,true);
assert.equal(cathflo.section42Present,true);
assert.notEqual(systemic.url,cathflo.url);
assert.equal(alteplase.publicationAllowed,false);
console.log('DRx first-100 source discovery wave A passed.');
