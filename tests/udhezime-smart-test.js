'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const E = require('../udhezime-smart.js');
const catalog = require('../data/icd-qkmf-hot-search-v1.json');
const file = name => fs.readFileSync(path.join(__dirname,'..',name),'utf8');
assert.equal(catalog.rows.length,72,'Expected live tracked DRX local catalog snapshot');
assert.equal(E.norm('KOLLË'), 'kolle');
assert.equal(E.searchICD(catalog.rows,'KOLLË')[0].code,'R05');
assert.equal(E.searchICD(catalog.rows,'palpitacione')[0].code,'R00.2');
assert.equal(E.searchICD(catalog.rows,'I10')[0].code,'I10');
assert.deepEqual(E.searchICD(catalog.rows,'zzsomething'),[]);
assert.equal(E.createDraft({}), '', 'Blank fields must generate no clinical narrative');
const f={reason:'Palpitacione',onset:'para tri ditësh',pulse:'110',sbp:'',dbp:'',temp:'',spo2:'',rr:'',weight:'',duration:'',associated:''};
const draft=E.createDraft(f);
assert.match(draft,/Palpitacione/);
assert.match(draft,/para tri ditësh/);
assert.match(draft,/110\/min/);
assert(!draft.includes('EKG'));
assert(!draft.includes('normal'));
assert(!draft.includes('120/80'));
assert(E.guidance('Dhimbje gjoksi','Kardiologji').danger);
assert(E.guidance('Hemiparez','Neurologji').danger);
assert(!E.guidance('Palpitacione','Kardiologji').danger);
assert(E.guidance('Kollë','Pulmologji').items.length>0);
assert.deepEqual(E.warnNumbers({spo2:'140'}),['Kontrollo vlerën e futur: SpO₂.']);
assert.deepEqual(E.warnNumbers({spo2:'97'}),[]);
assert.match(E.plain({patientName:'Pacient testues',reason:'kollë'}),/Pacient testues/);
assert(!E.plain({patientName:'Pacient testues'}).includes('EKZAMINIMI OBJEKTIV'));
const html=file('udhezime.html');
assert(html.includes('/udhezime-smart.css'));
assert(html.includes('/udhezime-smart.js'));
assert(html.includes('id="paperDetails"'));
assert(html.includes('id="icdResults"'));
assert(!/script[^>]+src=["']https?:/i.test(html));
const js=file('udhezime-smart.js');
assert(!/localStorage|sessionStorage|sendBeacon|XMLHttpRequest/.test(js),'No browser persistence or telemetry');
assert(js.includes("'/data/icd-qkmf-hot-search-v1.json'"));
const shell=file('index.html');
assert(shell.includes('href="/udhezime.html"'),'Main navigation should link to smart referrals');
console.log('DRX Udhëzime: katalogu, siguria, drafti, udhëzimet dhe lidhja e menusë OK.');
