'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');
const Policy=require('../lib/dose-source-policy.js');
const ROOT=path.resolve(__dirname,'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(ROOT,p),'utf8'));
const wave=read('data/drx-first100-source-discovery-wave-j-v1.json');
const decisions=read('data/drx-first100-canonical-review-decisions-v1.json');
const prior=['a','b','c','d','e','f','g','h','i'].flatMap(l=>read('data/drx-first100-source-discovery-wave-'+l+'-v1.json').rows);
assert.equal(wave.verifiedProductSpecificCount,1);
assert.equal(wave.rows.length,1);
assert.equal(wave.publicationAllowed,false);
const row=wave.rows[0];
const decision=decisions.decisions.find(d=>d.resolvedCanonicalKey===row.canonicalKey);
assert.ok(decision);
assert.equal(decision.sourceDiscoveryEligible,true);
assert.equal(decision.canonicalKey,row.resolvedFromCanonicalKey);
assert.equal(new Set(prior.map(x=>x.canonicalKey)).has(row.canonicalKey),false);
assert.equal(row.sourceTier,'AEMPS_CIMA');
assert.equal(Policy.sourceTierForUrl(row.url).key,'AEMPS_CIMA');
assert.equal(row.section41Present,true);
assert.equal(row.section42Present,true);
assert.equal(row.documentDate,'2023-02');
assert.equal(row.publicationAllowed,false);
console.log('DRx first-100 official source discovery wave J contract passed.');
