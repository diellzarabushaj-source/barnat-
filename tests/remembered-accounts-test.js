'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const stored=new Map();
const context={window:{},document:{querySelector(){return null}},localStorage:{getItem:key=>stored.get(key),setItem:(key,value)=>stored.set(key,value)}};
vm.runInNewContext(fs.readFileSync(require.resolve('../remembered-accounts.js'),'utf8'),context);
const api=context.window.DRxRememberedAccounts;
const login=(email,name)=>api.remember({authenticated:true,sessionVersion:3,supabaseAuthenticated:true,user:{email,name,password:'must-not-save'},refresh_token:'must-not-save',access_token:'must-not-save'});
login('one@example.test','First Doctor');login('two@example.test','Second Doctor');
assert.equal(api.list()[0].name,'Second Doctor');
assert.equal(api.list()[1].name,'First Doctor');
login('ONE@example.test','Updated Doctor');assert.equal(api.list().length,2);assert.equal(api.list()[0].name,'Updated Doctor');
assert.ok(![...stored.values()].join('').includes('must-not-save'));
api.remember({authenticated:false,user:{email:'attacker@example.test',name:'Unknown'}});assert.equal(api.list().length,2);
for(let i=0;i<10;i++)login(i+'@example.test','Doctor '+i);assert.equal(api.list().length,5);
stored.set('drx_remembered_accounts_v1','{broken');assert.equal(api.list().length,0);
context.localStorage.getItem=()=>{throw Error('Storage blocked')};assert.equal(api.list().length,0);
console.log('Remembered accounts passed: per-user names, deduplication, bounded metadata, no credentials, failed login and unavailable storage.');
