'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');
const Policy=require('../lib/dose-source-policy.js');
const ROOT=path.resolve(__dirname,'..');
const read=p=>JSON.parse(fs.readFileSync(path.join(ROOT,p),'utf8'));
const wave=read('data/drx-first100-source-discovery-wave-k-v1.json');
const quality=read('data/drx-first100-canonical-quality-audit-v1.json');
const prior=['a','b','c','d','e','f','g','h','i','j'].flatMap(l=>read('data/drx-first100-source-discovery-wave-'+l+'-v1.json').rows);
assert.equal(wave.verifiedProductSpecificCount,1);
assert.equal(wave.rows.length,1);
assert.equal(wave.publicationAllowed,false);
const row=wave.rows[0];
const eligible=new Set(quality.rows.filter(x=>x.sourceDiscoveryEligible).map(x=>x.canonicalKey));
assert.ok(eligible.has(row.canonicalKey));
assert.equal(new Set(prior.map(x=>x.canonicalKey)).has(row.canonicalKey),false);
assert.equal(row.sourceTier,'EU_NATIONAL');
assert.equal(Policy.sourceTierForUrl(row.url).key,'EU_NATIONAL');
assert.equal(row.section41Present,true);
assert.equal(row.section42Present,true);
assert.equal(row.documentDate,'2019-05-31');
assert.equal(row.publicationAllowed,false);
assert.match(row.productName,/MECLON/i);
console.log('DRx first-100 official source discovery wave K contract passed.');
