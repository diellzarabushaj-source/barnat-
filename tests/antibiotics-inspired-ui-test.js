assert.doesNotMatch(html,/https:\/\/cdn\.jsdelivr\.net|https:\/\/unpkg\.com|https:\/\/fonts\.googleapis\.com/,'Do not introduce external scripts or fonts');
assert.match(css,/prefers-reduced-motion:reduce/);
assert.match(css,/@media\(hover:none\),\(pointer:coarse\)/);
