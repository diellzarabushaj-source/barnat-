'use strict';
const assert=require('node:assert/strict');
const Gate=require('../scripts/audit-drx-batch2-prepublication.js');
const Packets=require('../scripts/build-drx-batch2-review-packets.js');

const g=Gate.audit();
assert.equal(g.total,25);
assert.equal(g.publishable,0);
assert.equal(g.blocked,25);
assert.equal(g.pass,true);
assert.equal(g.publicationAllowed,false);
const policy=require('../data/drx-publication-gate-v3-policy.json');
assert.equal(policy.bulkImporterMayPublish,false);
assert.ok(policy.publishWhenAll.includes('source_section_sha256_present'));
assert.ok(policy.publishWhenAll.includes('required_renal_adjustments_verified_if_required'));
assert.ok(policy.publishWhenAll.includes('required_hepatic_adjustments_verified_if_required'));
assert.ok(policy.publishWhenAll.includes('reviewer_audit_complete'));

const p=Packets.build();
assert.equal(p.total,25);
assert.equal(p.publicationAllowed,false);
assert.ok(p.packets.every(x=>x.status==='pending_clinical_review'));
assert.ok(p.packets.every(x=>Array.isArray(x.requiredDecisions)&&x.requiredDecisions.length>=8));
assert.ok(p.packets.every(x=>x.requiredDecisions.includes('confirm_source_snapshot_and_section_hash')));
assert.ok(p.packets.every(x=>x.requiredDecisions.includes('confirm_exact_product_can_supply_rule')));
assert.ok(p.packets.every(x=>x.requiredDecisions.includes('confirm_legacy_comparison')));
assert.ok(p.packets.every(x=>x.requiredDecisions.includes('confirm_safety_validation')));
assert.ok(p.packets.every(x=>x.requiredDecisions.includes('confirm_reviewer_identity_and_reason')));
assert.ok(p.packets.every(x=>x.sourceSnapshotId===null&&x.sourceSection==='4.2'&&x.sourceSectionSha256===null));
assert.ok(p.packets.every(x=>x.reviewerId===null&&x.reviewedAt===null&&x.decisionReason===null));
assert.ok(p.packets.every(x=>x.reviewEvidenceReady===false));
assert.ok(p.packets.find(x=>x.canonicalKey==='ciprofloxacin').requiredDecisions.includes('confirm_antimicrobial_guidance_context'));
assert.ok(p.packets.find(x=>x.canonicalKey==='spironolactone').requiredDecisions.includes('confirm_renal_adjustment_logic'));
assert.ok(p.packets.find(x=>x.canonicalKey==='tramadol').requiredDecisions.includes('confirm_high_risk_manual_review'));
console.log('DRx Batch 2 prepublication and review packet contracts passed.');
