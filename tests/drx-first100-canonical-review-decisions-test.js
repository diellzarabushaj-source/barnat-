'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');
const x=JSON.parse(fs.readFileSync(path.join(__dirname,'..','data','drx-first100-canonical-review-decisions-v1.json'),'utf8'));
assert.equal(x.total,13);
assert.equal(x.resolved,13);
assert.equal(x.pending,0);
assert.equal(x.effectiveSourceDiscoveryEligible,89);
assert.equal(x.effectiveUniqueSourceDiscoveryEligible,89);
assert.equal(x.publicationAllowed,false);
assert.equal(x.canonicalReviewOpen,0);
assert.equal(x.queueRegenerationRequired,true);
assert.equal(x.refillRowsRequired,10);
assert.deepEqual(x.dispositionCounts,{dedupeExistingCanonical:3,replaceWithCleanCanonical:2,removeProductLevelMixture:7,requiresProductSelection:1});
const beta=x.decisions.find(d=>d.canonicalKey==='betamethasonedipropionateequivalntbetamethasone');
assert.equal(beta.decision,'resolved_equivalence_not_combination');
assert.equal(beta.resolvedCanonicalKey,'betamethasonedipropionate');
assert.ok(x.resolutionNotes.some(note=>/already[- ]existing/.test(note)));
assert.ok(beta.evidence.some(e=>/medicines\.org\.uk/.test(e.url)));
const amlo=x.decisions.find(d=>d.canonicalKey==='amlodipinebesilate2ramipril');
assert.equal(amlo.decision,'resolved_typo_and_salt_equivalence_not_extra_component');
assert.equal(amlo.resolvedCanonicalKey,'amlodipineramipril');
assert.equal(amlo.resolvedCanonicalName,'Amlodipine + Ramipril');
assert.equal(amlo.sourceDiscoveryEligible,true);
assert.equal(amlo.publicationAllowed,false);
assert.ok(amlo.evidence.some(e=>e.authority==='AEMPS_CIMA' && /cima\.aemps\.es/.test(e.url)));
const pancreatin=x.decisions.find(d=>d.resolvedCanonicalKey==='pancreatin');
assert.equal(pancreatin.decision,'resolved_enzyme_activity_expression_to_pancreatin');
assert.equal(pancreatin.sourceDiscoveryEligible,true);
assert.ok(pancreatin.evidence.some(e=>/medicines\.org\.uk\/emc\/product\/1167/.test(e.url)));
const calcipotriol=x.decisions.find(d=>d.canonicalKey==='calcipotriolcombinations');
assert.equal(calcipotriol.queueDisposition,'requires_product_selection');
assert.equal(calcipotriol.productSelectionRequired,true);
const removed=x.decisions.filter(d=>d.queueDisposition==='remove_product_level_mixture');
assert.equal(removed.length,7);
assert.ok(x.decisions.every(d=>d.dispositionResolved===true&&d.canonicalIdentityResolved===true));
console.log('DRx first-100 canonical review decisions passed.');
