'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { verifyArchive, buildClinicalReviewQueue, buildClinicalDraftBatch } = require('../lib/registry-clinical-review');
const Archive = require('../lib/dose-source-archive');
const SmPC = require('../lib/smpc-parser');
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'registry-clinical-review-'));
try {
  const raw = Buffer.from('<h1>Example medicine</h1><h2>4.1 Therapeutic indications</h2><p>Example use</p><h2>4.2 Posology</h2><p>Example reference dose</p><h2>4.3 Contraindications</h2><p>Example restriction</p>');
  const parsed = SmPC.extractClinicalSections(raw.toString());
  const rawSha256 = hash(raw);
  const sectionSha256 = Object.fromEntries(Object.entries(parsed.sections).map(([key, value]) => [key, hash(value.text)]));
  const snapshot = { raw, rawSha256, snapshotId: rawSha256, parsed, parser: {}, sectionSha256, sourceDocument: { productName: 'Example medicine', documentDate: '2026-01-01' }, fetchedAt: '2026-10-05T00:00:00Z', finalUrl: 'https://www.medicines.org.uk/emc/product/123/smpc' };
  const files = Archive.writeSnapshot(snapshot, dir);
  const evidence = { ...snapshot, url: snapshot.finalUrl, files }; delete evidence.raw; delete evidence.parsed;
  assert.equal(verifyArchive(evidence).rawSha256, rawSha256);
  const example = { id: 'test-new', trade_name: 'Example', strength: '5 mg', pharmaceutical_form: 'Tablet', update_status: 'E re', is_published: false };
  const exampleQueue = buildClinicalReviewQueue([{ product: example }], [evidence], { sourceSha256: '1'.repeat(64), discoveredSources: { 'test-new': [evidence.url] } });
  const draft = { drugId: example.id, tradeName: 'Example', strength: '5 mg', pharmaceuticalForm: 'Tablet', bindingStatus: 'product_specific_candidate', publicationAllowed: false, documentDate: '2026-01-01', drugClass: 'Example class', useText: 'Example use', adultDose: 'Example adult proposal', pediatricDose: 'No pediatric dose in this reference', route: 'PO', sourceUrl: evidence.url, sourceRawSha256: rawSha256, sectionSha256 };
  const draftBatch = { sourceSha256: exampleQueue.sourceSha256, entries: [draft] };
  assert.equal(buildClinicalDraftBatch(exampleQueue, draftBatch, [evidence]).entries.length, 1);
  assert.throws(() => buildClinicalDraftBatch(exampleQueue, { ...draftBatch, entries: [{ ...draft, strength: '10 mg' }] }, [evidence]), /identity mismatch/);
  assert.throws(() => buildClinicalDraftBatch(exampleQueue, { ...draftBatch, entries: [{ ...draft, publicationAllowed: true }] }, [evidence]), /unpublished candidate/);
  assert.throws(() => buildClinicalDraftBatch(exampleQueue, { ...draftBatch, entries: [{ ...draft, pediatricDose: '' }] }, [evidence]), /proposal field/);
  assert.throws(() => buildClinicalDraftBatch(exampleQueue, { ...draftBatch, entries: [draft, draft] }, [evidence]), /duplicate/);
  assert.throws(() => verifyArchive({ ...evidence, rawSha256: '0'.repeat(64) }), /metadata raw hash mismatch/);
  const metadata = JSON.parse(fs.readFileSync(files.metaPath, 'utf8'));
  fs.writeFileSync(files.metaPath, JSON.stringify({ ...metadata, sectionSha256: { ...metadata.sectionSha256, '4.2': '0'.repeat(64) } }));
  assert.throws(() => verifyArchive(evidence), /Archived metadata section hash mismatch/);
  fs.writeFileSync(files.metaPath, JSON.stringify(metadata));
  fs.writeFileSync(files.rawPath, Buffer.from('tampered source'));
  assert.throws(() => verifyArchive(evidence), /raw hash mismatch/);
} finally {
  for (const file of fs.readdirSync(dir)) fs.unlinkSync(path.join(dir, file));
  fs.rmdirSync(dir);
}
const product = { id: 'new-product', update_status: 'E re', is_published: false, editorial_status: 'in_review', atc_code: 'A01AA01', trade_name: 'New example', pharmaceutical_form: 'Tablet' };
const rows = [{ product, candidates: [{ drug: { id: 'existing-reference', trade_name: 'Reference', drug_class: 'Reference class', use_text: 'Reference use' }, profile: { source_urls: ['https://example.org/reference'] }, regimens: [{ population: 'adult', dose_text: 'Reference only', editorial_status: 'published', source_url: 'https://example.org/reference' }] }] }];
const options = { sourceSha256: '1'.repeat(64) };
const queue = buildClinicalReviewQueue(rows, [], options);
assert.equal(queue.summary.products, 1);
assert.equal(queue.summary.needsSource, 1);
assert.equal(queue.entries[0].references[0].verificationStatus, 'in_review');
assert.equal(queue.entries[0].references[0].publicationAllowed, false);
assert.equal(queue.entries[0].references[0].proposedAdultDoses[0].text, 'Reference only');
assert.equal(queue.entries[0].sources.length, 0);
assert.throws(() => buildClinicalReviewQueue([...rows, ...rows], [], options), /unique unpublished/);
assert.throws(() => buildClinicalReviewQueue([{ product: { ...product, is_published: true } }], [], options), /unique unpublished/);
assert.throws(() => buildClinicalReviewQueue([{ product: { ...product, editorial_status: 'archived' } }], [], options), /unique unpublished/);
assert.throws(() => buildClinicalReviewQueue(rows, [], {}), /document hash/);
assert.equal(verifyArchive({ error: 'HTTP 404' }), null);
assert.equal(verifyArchive({ url: 'https://unverified.example.org/document' }), null);
console.log('registry clinical review tests passed');
